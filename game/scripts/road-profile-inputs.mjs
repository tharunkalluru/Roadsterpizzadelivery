const GENERATED = new Set(['src/world/road-profile-corrections.json', 'src/world/road-profile-cache-manifest.json', 'public/city/road-profiles-v1.pack.wasm']);
export async function roadProfileInputFiles(root) {
  const files = [...ROAD_PROFILE_INPUTS];
  const collect = async dir => {
    for (const entry of await readdir(resolve(root, dir), { withFileTypes: true })) {
      const file = join(dir, entry.name).split('\\').join('/');
      if (entry.isSymbolicLink()) throw Error(`Linked road profile input: ${file}`);
      if (entry.isDirectory()) await collect(file);
      else if (entry.isFile() && !GENERATED.has(file)) files.push(file);
    }
  };
  await collect('src');
  // Tile-only source streets also participate in modeled-node transport. Their
  // packs must invalidate a solve even when the core inventory stays unchanged.
  await collect('public/city');
  return [...new Set(files)].sort();
}
export async function roadProfileInputFingerprint(root) {
  const hash = createHash('sha256');
  for (const file of await roadProfileInputFiles(root)) {
    const bytes = await readFile(resolve(root, file));
    hash.update(file + '\0').update(String(bytes.length)).update('\0').update(bytes);
  }
  return hash.digest('hex');
}
