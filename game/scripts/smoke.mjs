// Browser smoke run against a running server: node scripts/smoke.mjs <url> <outdir> [--autopilot]
import { chromium } from '@playwright/test';
const url = process.argv[2] ?? 'http://localhost:5173/';
const out = process.argv[3] ?? 'qa/artifacts/smoke';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
const logs = [];
p.on('console', (m) => logs.push(`[${m.type()}] ${m.text()}`));
p.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
await p.goto(url);
await p.waitForFunction(() => window.__hmd && (window.__hmd.state === 'MENU' || window.__hmd.state === 'ERROR'), null, { timeout: 120000 });
await p.screenshot({ path: `${out}/01-menu.png` });
console.log('state', await p.evaluate(() => window.__hmd.state), 'missions', await p.evaluate(() => window.__hmd.missions.map((m) => `${m.id}:${m.routeLengthM}m/${m.deadlineSeconds}s`).join(' ')));
await p.click('[data-play]');
await p.click('[data-m]');
await p.screenshot({ path: `${out}/02-preview.png` });
await p.click('[data-go]');
await p.waitForFunction(() => window.__hmd.state === 'READY' || window.__hmd.state === 'ERROR', null, { timeout: 180000 });
await p.screenshot({ path: `${out}/03-ready.png` });
await p.click('[data-start]');
await p.waitForFunction(() => window.__hmd.state === 'PLAYING', null, { timeout: 120000 }).catch(async (e) => { console.log('stuck', await p.evaluate(() => ({ s: window.__hmd.state, f: window.__hmd.frameStats() }))); throw e; });
await p.keyboard.down('ArrowUp');
await p.waitForTimeout(4000);
await p.screenshot({ path: `${out}/04-driving.png` });
await p.keyboard.press('Space');
await p.waitForTimeout(3500);
await p.screenshot({ path: `${out}/05-flying.png` });
console.log(await p.evaluate(() => { const s = window.__hmd.session; return { tick: s.tick, move: s.player.move, consumed: s.player.ledger.consumedTicks, fps: window.__hmd.frameStats(), stats: window.__hmd.view.stats }; }));
await p.waitForTimeout(6000);
await p.screenshot({ path: `${out}/06-later.png` });
console.log(logs.slice(0, 40).join('\n'));
await b.close();
