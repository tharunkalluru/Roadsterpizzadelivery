// Headless smoke test of the playable build: node tools/playtest.mjs outdir
import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const out = process.argv[2] || '.';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 640 } });
const errs = [];
page.on('pageerror', e => errs.push(e.message));
page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
await page.goto('http://127.0.0.1:4173/?q=high&area=RTC%20X%20Roads');
await page.waitForFunction(() => window.__game || window.__err, null, { timeout: 300000 });
const state = () => page.evaluate(() => { const g = window.__game; return g && { coins: g.coins, order: g.order && g.order.state, pos: [g.player.pos.x.toFixed(1), g.player.pos.y.toFixed(1), g.player.pos.z.toFixed(1)], speed: g.player.speed.toFixed(1), cars: g.traffic.cars.length, day: g.day, min: Math.round(g.minutes), route: g.route ? Math.round(g.route.len) : null, err: window.__err }; });
await page.waitForTimeout(6000);
console.log('start', JSON.stringify(await state()));
await page.screenshot({ path: `${out}/play1.png`, timeout: 180000 });
await page.keyboard.press('KeyE');
await page.waitForTimeout(1500);
console.log('accepted', JSON.stringify(await state()));
await page.keyboard.down('KeyW');
await page.waitForTimeout(5000);
await page.screenshot({ path: `${out}/play2.png`, timeout: 180000 });
console.log('driving', JSON.stringify(await state()));
await page.keyboard.press('Space');
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/play3.png`, timeout: 180000 });
console.log('flying', JSON.stringify(await state()));
await page.keyboard.up('KeyW');
await page.keyboard.press('KeyT');
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/play4.png`, timeout: 180000 });
console.log('errors', errs.slice(0, 8));
await browser.close();
